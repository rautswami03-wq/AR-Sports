export const DEFAULT_THEME_ID: ThemeId = 'nakshatra';

/** Get a theme by ID, falling back to nakshatra */
export function getTheme(id: string | null | undefined): ScoreboardTheme {
  if (id && id in SCOREBOARD_THEMES) {
    return SCOREBOARD_THEMES[id as ThemeId];
  }
  return SCOREBOARD_THEMES[DEFAULT_THEME_ID];
}

/** Inject a theme's CSS custom properties onto a DOM element */
export function applyThemeToDom(theme: ScoreboardTheme, el: HTMLElement = document.documentElement): void {
  const vars: Record<string, string> = {
    '--sb-bg-primary': theme.bgPrimary,
    '--sb-bg-secondary': theme.bgSecondary,
    '--sb-bg-accent': theme.bgAccent,
    '--sb-bg-ticker': theme.bgTicker,
    '--sb-text-primary': theme.textPrimary,
    '--sb-text-secondary': theme.textSecondary,
    '--sb-text-accent': theme.textAccent,
    '--sb-text-muted': theme.textMuted,
    '--sb-accent-primary': theme.accentPrimary,
    '--sb-accent-secondary': theme.accentSecondary,
    '--sb-accent-gold': theme.accentGold ?? theme.accentPrimary,
    '--sb-border-color': theme.borderColor,
    '--sb-glow-color': theme.glowColor,
    '--sb-glow-strength': theme.glowStrength,
    '--sb-ball-dot-0': theme.ballDot0,
    '--sb-ball-dot-1': theme.ballDot1,
    '--sb-ball-dot-4': theme.ballDot4,
    '--sb-ball-dot-6': theme.ballDot6,
    '--sb-ball-dot-w': theme.ballDotW,
    '--sb-ball-dot-wd': theme.ballDotWD,
    '--sb-ball-dot-nb': theme.ballDotNB,
    '--sb-flash-four': theme.flashFour,
    '--sb-flash-six': theme.flashSix,
    '--sb-flash-wicket': theme.flashWicket,
    '--sb-flash-extra': theme.flashExtra,
    '--sb-font-primary': theme.fontPrimary,
    '--sb-font-mono': theme.fontMono ?? theme.fontPrimary,
    '--sb-border-radius': theme.borderRadius,
    '--sb-strip-height': theme.stripHeight,
    '--sb-backdrop-blur': theme.backdropBlur ?? '0px',
  };
  for (const [k, v] of Object.entries(vars)) {
    el.style.setProperty(k, v);
  }
}

