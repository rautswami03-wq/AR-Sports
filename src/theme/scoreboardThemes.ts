export interface ScoreboardTheme {
  id: ThemeId;
  name: string;
  description: string;

  // ── CSS Custom Property values injected at runtime ──
  bgPrimary: string;        // Main strip background
  bgSecondary: string;      // Batter/bowler panel background
  bgAccent: string;         // Score box, team badge background
  bgTicker: string;         // Bottom ticker background
  bgGlass?: string;         // glassmorphism overlay color

  textPrimary: string;      // Main labels
  textSecondary: string;    // Sub-labels, secondary info
  textAccent: string;       // Highlighted numbers (score, strike)
  textMuted: string;        // Balls, SR, economy — muted

  accentPrimary: string;    // Main accent (borders, glows, badges)
  accentSecondary: string;  // Secondary accent
  accentGold?: string;      // Optional gold for special moments

  borderColor: string;      // Panel borders
  glowColor: string;        // CSS box-shadow glow color
  glowStrength: string;     // e.g. '0 0 20px'

  // Ball dot colors
  ballDot0: string;         // dot ball
  ballDot1: string;         // 1 run
  ballDot4: string;         // four
  ballDot6: string;         // six
  ballDotW: string;         // wicket
  ballDotWD: string;        // wide
  ballDotNB: string;        // no-ball

  // Flash colors
  flashFour: string;
  flashSix: string;
  flashWicket: string;
  flashExtra: string;

  // Fonts
  fontPrimary: string;      // Google Fonts family name
  fontMono?: string;        // Monospace for digits
  fontUrl?: string;         // Google Fonts @import URL

  // Layout & animation
  layoutVariant: LayoutVariant;
  animationVariant: AnimationVariant;
  celebrationStyle: CelebrationStyle;

  // Visual style
  borderRadius: string;     // Border radius tokens
  stripHeight: string;      // px height of main strip
  backdropBlur?: string;    // for glass themes
  backgroundPattern?: string; // CSS gradient/pattern for body
  teamBadgeStyle: 'pill' | 'square' | 'angled' | 'circle';

  // Special flags
  isLight: boolean;         // light theme → invert some defaults
  hasAnimatedBg: boolean;   // animated gradient background
  showHundredBalls: boolean; // The Hundred layout — show 100-ball counter
}

